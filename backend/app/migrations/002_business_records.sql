CREATE TABLE businesses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_row INTEGER NOT NULL,
    source_year SMALLINT,
    founding_year SMALLINT,
    first_appearance SMALLINT,
    appearance_decade TEXT,
    end_year SMALLINT,
    if_closed BOOLEAN,
    biz_name TEXT NOT NULL,
    broad_industry TEXT,
    industry1 TEXT,
    race TEXT,
    gender TEXT,
    owner_name TEXT,
    ownership_type TEXT,
    ownership_demographic TEXT,
    address TEXT,
    postal TEXT,
    point_x DOUBLE PRECISION,
    point_y DOUBLE PRECISION,
    old_address TEXT,
    phone_number TEXT,
    website TEXT,
    social_media BOOLEAN,
    facebook_url TEXT,
    instagram_url TEXT,
    youtube_url TEXT,
    x_url TEXT,
    linkedin_url TEXT,
    source_id TEXT,
    newspaper TEXT,
    city_directories BOOLEAN,
    google_modern_business BOOLEAN,
    link_oh_interview TEXT,
    link_gbh_story TEXT,
    biz_id TEXT NOT NULL,
    notes TEXT,
    CONSTRAINT businesses_source_year_range
        CHECK (source_year IS NULL OR source_year BETWEEN 1800 AND 2100),
    CONSTRAINT businesses_founding_year_range
        CHECK (founding_year IS NULL OR founding_year BETWEEN 1800 AND 2100),
    CONSTRAINT businesses_first_appearance_range
        CHECK (first_appearance IS NULL OR first_appearance BETWEEN 1800 AND 2100),
    CONSTRAINT businesses_end_year_range
        CHECK (end_year IS NULL OR end_year BETWEEN 1800 AND 2100),
    CONSTRAINT businesses_appearance_decade_format
        CHECK (appearance_decade IS NULL OR appearance_decade ~ '^[0-9]{4}s$'),
    CONSTRAINT businesses_postal_format
        CHECK (postal IS NULL OR postal ~ '^[0-9]{5}$'),
    CONSTRAINT businesses_point_x_range
        CHECK (point_x IS NULL OR point_x BETWEEN -180 AND 180),
    CONSTRAINT businesses_point_y_range
        CHECK (point_y IS NULL OR point_y BETWEEN -90 AND 90)
);

CREATE INDEX businesses_biz_id_idx ON businesses (biz_id);
CREATE INDEX businesses_broad_industry_idx ON businesses (broad_industry);
CREATE INDEX businesses_appearance_decade_idx ON businesses (appearance_decade);
CREATE INDEX businesses_biz_name_lower_idx ON businesses (LOWER(biz_name));
